import { readFile, writeFile } from 'node:fs/promises';
import { encode } from '../src/payload.js';

const root = new URL('../', import.meta.url);
const entries = JSON.parse(await readFile(new URL('data/examples.json', root), 'utf8'));
const links = [];
for (const entry of entries) {
  const source = await readFile(new URL(`examples/${entry.id}.js`, root), 'utf8');
  const { hash, bytes } = await encode(source);
  if (bytes > 3072) throw new Error(`${entry.id} exceeds the shared game limit`);
  links.push({ ...entry, hash });
}
const target = new URL('src/example-links.js', root);
const output =
  '// Generated by npm run examples.\nexport const exampleLinks = ' +
  JSON.stringify(links, null, 2) +
  ';\n';
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== output)
    throw new Error('Example links are stale; run npm run examples');
} else await writeFile(target, output);
